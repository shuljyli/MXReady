"""Generate public schema and frontend response types from the backend models."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from mxready.models import ScanJob, ScanReport, VerificationRun

ROOT = Path(__file__).resolve().parents[1]


def typescript_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(typescript_type(item) for item in schema["anyOf"]))
    kind = str(schema.get("type"))
    if kind == "array":
        return f"Array<{typescript_type(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            properties = "; ".join(
                f"{key}: {typescript_type(value)}" for key, value in schema["properties"].items()
            )
            return "{ " + properties + " }"
        return f"Record<string, {typescript_type(schema.get('additionalProperties', {}))}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def artifacts() -> dict[Path, str]:
    definitions: dict[str, Any] = {}
    for model in (ScanJob, ScanReport):
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    declarations = ["// Generated by scripts/generate_contracts.py; do not edit.\n"]
    for name, schema in sorted(definitions.items()):
        if "properties" in schema:
            declarations.append(f"export type {name} = {{")
            declarations.extend(
                f"  {key}: {typescript_type(value)};" for key, value in schema["properties"].items()
            )
            declarations.append("};\n")
        else:
            declarations.append(f"export type {name} = {typescript_type(schema)};\n")
    verification = VerificationRun.model_json_schema()
    verification["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    return {
        ROOT / "frontend/src/api/generated.ts": "\n".join(declarations),
        ROOT / "src/mxready/resources/schemas/verification-result-v1.json": json.dumps(
            verification, indent=2, ensure_ascii=False
        )
        + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in artifacts().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Outdated generated contracts: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
